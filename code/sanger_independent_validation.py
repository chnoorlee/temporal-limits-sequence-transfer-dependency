def _portable_path(path: Path) -> str:
    """Represent project files relative to the project root when possible."""
    resolved = path.resolve()
    root = ROOT.resolve()
    try:
        return resolved.relative_to(root).as_posix()
    except ValueError:
        return str(resolved)


def _resolve_bound_path(value: Any, *, label: str = "bound path") -> Path:
    if not isinstance(value, str) or not value:
        raise ValidationError(f"{label} must be a non-empty string")
    candidate = Path(value)
    if candidate.is_absolute():
        return candidate.resolve()
    root = ROOT.resolve()
    resolved = (root / candidate).resolve()
    try:
        resolved.relative_to(root)
    except ValueError as exc:
        raise ValidationError(f"{label} escapes the project root: {value}") from exc
    return resolved


def _resolve_campaign_run_path(value: Any) -> Path:
    """Resolve a campaign run path against the workspace, never process CWD."""
    return _resolve_bound_path(value, label="campaign source run path")


