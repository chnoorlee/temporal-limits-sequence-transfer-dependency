def _copy_bound_snapshot(
    source: Path,
    destination: Path,
    expected: Mapping[str, Any],
    *,
    label: str,
) -> None:
    """Create an fsynced private copy while checking the source before and after."""
    _verify_record(source, expected, label=f"{label} source before snapshot")
    destination.parent.mkdir(parents=True, exist_ok=True)
    try:
        with source.open("rb") as reader, destination.open("xb") as writer:
            before = os.fstat(reader.fileno())
            while chunk := reader.read(4 * 1024 * 1024):
                writer.write(chunk)
            after = os.fstat(reader.fileno())
            writer.flush()
            os.fsync(writer.fileno())
    except OSError as exc:
        raise ValidationError(f"cannot create {label} snapshot") from exc
    if _stat_signature(before) != _stat_signature(after):
        raise ValidationError(f"{label} changed while its snapshot was created")
    _verify_record(source, expected, label=f"{label} source after snapshot")
    _verify_record(destination, expected, label=f"{label} snapshot")


def _campaign_dependency_inventory(
    report: Mapping[str, Any],
) -> list[dict[str, Any]]:
    inventory: list[dict[str, Any]] = []
    for run in report.get("source_runs", []):
        if not isinstance(run, Mapping):
            raise ValidationError("campaign source run record is not an object")
        run_path = _resolve_campaign_run_path(run.get("path"))
        artifacts: list[dict[str, Any]] = []
        for filename in (
            "completion.json",
            "summary.json",
            "run-manifest.json",
            "cohort-manifest.json",
        ):
            artifacts.append(
                {
                    "logical_path": filename,
                    **_record_dict(_file_record(run_path / filename)),
                }
            )
        fold_artifacts = run.get("fold_artifacts")
        if not isinstance(fold_artifacts, list):
            raise ValidationError("campaign fold artifact inventory is invalid")
        for artifact in fold_artifacts:
            if not isinstance(artifact, Mapping):
                raise ValidationError("campaign fold artifact record is not an object")
            relative = artifact.get("path")
            artifacts.append(
                {
                    "logical_path": relative,
                    **_record_dict(_file_record(_safe_child(run_path, relative))),
                }
            )
        inventory.append(
            {
                "key": run.get("key"),
                "run_path": _portable_path(run_path),
                "artifacts": artifacts,
            }
        )
    return inventory


