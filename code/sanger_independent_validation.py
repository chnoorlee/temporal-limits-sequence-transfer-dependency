def _write_tsv(
    path: Path, rows: Iterable[Mapping[str, Any]], fields: Sequence[str]
) -> None:
    payload = _canonical_tsv_bytes(rows, fields)
    with path.open("wb") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())


def _canonical_tsv_bytes(
    rows: Iterable[Mapping[str, Any]], fields: Sequence[str]
) -> bytes:
    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(
        buffer, fieldnames=list(fields), delimiter="\t", lineterminator="\n"
    )
    writer.writeheader()
    for row in rows:
        writer.writerow({field: row.get(field) for field in fields})
    return buffer.getvalue().encode("utf-8")


def write_formal_run(
    analysis: Mapping[str, Any], bindings: Mapping[str, Any], output_root: Path
) -> Path:
    if (
        analysis.get("scientific_result") is not True
        or analysis.get("fixture") is not False
    ):
        raise ValidationError(
            "only a non-fixture scientific analysis can be published formally"
        )
    output_root.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%dT%H%M%S", time.gmtime())
    name = f"{stamp}.{time.time_ns() % 1_000_000_000:09d}Z-{uuid.uuid4().hex[:8]}"
    staging = output_root / f".{name}.tmp-{uuid.uuid4().hex}"
    destination = output_root / name
    staging.mkdir(exist_ok=False)
    try:
        _atomic_json(staging / "analysis.json", dict(analysis))
        _atomic_json(staging / "source-bindings.json", dict(bindings))
        _write_tsv(
            staging / "matched-cells.tsv",
            bindings["cell_matches"],
            CELL_MATCH_FIELDS,
        )
        _write_tsv(
            staging / "matched-genes.tsv",
            bindings["gene_matches"],
            GENE_MATCH_FIELDS,
        )
        artifacts = [
            _record_dict(_file_record(staging / name)) for name in FORMAL_ARTIFACT_NAMES
        ]
        for record in artifacts:
            record["path"] = Path(record["path"]).name
        completion = {
            "schema": COMPLETION_SCHEMA,
            "scientific_result": True,
            "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "artifacts": artifacts,
            "analysis_canonical_sha256": hashlib.sha256(
                _canonical_json_bytes(analysis)
            ).hexdigest(),
        }
        _atomic_json(staging / "completion.json", completion)
        trusted_completion_sha256 = _sha256_file(staging / "completion.json")
        verification = verify_run(
            staging,
            trusted_completion_sha256=trusted_completion_sha256,
        )
        if (
            verification.get("verified") is not True
            or verification.get("scientific_result") is not True
        ):
            raise ValidationError(
                "staged formal Sanger run did not pass independent verification"
            )
        os.replace(staging, destination)
    except Exception:
        for child in staging.iterdir() if staging.exists() else ():
            child.unlink(missing_ok=True)
        staging.rmdir() if staging.exists() else None
        raise
    return destination


def verify_run(run_dir: Path, *, trusted_completion_sha256: str) -> dict[str, Any]:
    run_dir = run_dir.resolve()
    if not _valid_sha256(trusted_completion_sha256):
        raise ValidationError(
            "trusted completion SHA-256 must be an externally supplied lowercase digest"
        )
    completion_path = run_dir / "completion.json"
    completion, completion_record = _read_json_object(
        completion_path, label="formal Sanger completion"
    )
    if completion_record.sha256 != trusted_completion_sha256:
        raise ValidationError(
            "completion.json does not match the externally trusted SHA-256"
        )
    if completion.get("schema") != COMPLETION_SCHEMA:
        raise ValidationError("formal Sanger completion schema is invalid")
    if completion.get("scientific_result") is not True:
        raise ValidationError("formal Sanger completion is not scientific")
    artifacts = completion.get("artifacts")
    if not isinstance(artifacts, list):
        raise ValidationError("formal Sanger artifact inventory is invalid")
    if not all(isinstance(record, dict) for record in artifacts):
        raise ValidationError("formal Sanger artifact records are invalid")
    artifact_names = [record.get("path") for record in artifacts]
    if artifact_names != list(FORMAL_ARTIFACT_NAMES):
        raise ValidationError(
            "formal Sanger artifact inventory must contain each fixed artifact "
            "exactly once in canonical order"
        )
    artifact_records = dict(zip(FORMAL_ARTIFACT_NAMES, artifacts, strict=True))
    artifact_paths = {
        name: _safe_child(run_dir, name) for name in FORMAL_ARTIFACT_NAMES
    }

    analysis, analysis_record = _read_json_object(
        artifact_paths["analysis.json"], label="formal Sanger analysis"
    )
    _assert_observed_record(
        analysis_record,
        artifact_records["analysis.json"],
        label="completion.artifacts[0]",
        check_path=False,
    )
    bindings, bindings_record = _read_json_object(
        artifact_paths["source-bindings.json"],
        label="formal Sanger source bindings",
    )
    _assert_observed_record(
        bindings_record,
        artifact_records["source-bindings.json"],
        label="completion.artifacts[1]",
        check_path=False,
    )
    table_payloads: dict[str, bytes] = {}
    for index, name in enumerate(FORMAL_ARTIFACT_NAMES[2:], start=2):
        payload, observed = _stable_read_bytes(artifact_paths[name])
        _assert_observed_record(
            observed,
            artifact_records[name],
            label=f"completion.artifacts[{index}]",
            check_path=False,
        )
        table_payloads[name] = payload

    if (
        analysis.get("scientific_result") is not True
        or analysis.get("fixture") is not False
    ):
        raise ValidationError("formal Sanger analysis is not a non-fixture result")
    if hashlib.sha256(_canonical_json_bytes(analysis)).hexdigest() != completion.get(
        "analysis_canonical_sha256"
    ):
        raise ValidationError("analysis canonical hash does not match completion")

    expected_bindings = {
        "campaign_report": _record_path(
            bindings["campaign_report"], label="source-bindings.campaign_report"
        ),
        "protocol_freeze": _record_path(
            bindings["protocol_freeze"], label="source-bindings.protocol_freeze"
        ),
        "zip_path": _record_path(
            bindings["external_archive"], label="source-bindings.external_archive"
        ),
        "model_csv": _record_path(
            bindings["model_csv"], label="source-bindings.model_csv"
        ),
        "cells_path": _record_path(
            bindings["cohort_cells"], label="source-bindings.cohort_cells"
        ),
        "genes_path": _record_path(
            bindings["cohort_genes"], label="source-bindings.cohort_genes"
        ),
        "archive_spec": _archive_spec_from_dict(bindings.get("external_archive_spec")),
        "fixture": False,
    }
    for key, path in expected_bindings.items():
        if key in {"archive_spec", "fixture"}:
            continue
        binding_key = {
            "zip_path": "external_archive",
            "cells_path": "cohort_cells",
            "genes_path": "cohort_genes",
        }.get(key, key)
        _verify_record(
            path, bindings[binding_key], label=f"source-bindings.{binding_key}"
        )
    _verify_record(
        _record_path(
            bindings["analysis_source"], label="source-bindings.analysis_source"
        ),
        bindings["analysis_source"],
        label="source-bindings.analysis_source",
    )
    recomputed, recomputed_bindings = build_analysis(**expected_bindings)
    if _canonical_json_bytes(recomputed) != _canonical_json_bytes(analysis):
        raise ValidationError(
            "independently recomputed analysis differs from stored analysis"
        )
    if recomputed_bindings != bindings:
        raise ValidationError(
            "independently recomputed source bindings differ from stored bindings"
        )
    expected_tables = {
        "matched-cells.tsv": _canonical_tsv_bytes(
            recomputed_bindings["cell_matches"], CELL_MATCH_FIELDS
        ),
        "matched-genes.tsv": _canonical_tsv_bytes(
            recomputed_bindings["gene_matches"], GENE_MATCH_FIELDS
        ),
    }
    for name, expected in expected_tables.items():
        if table_payloads[name] != expected:
            raise ValidationError(
                f"formal Sanger audit table differs from deterministic reconstruction: {name}"
            )
    for index, name in enumerate(FORMAL_ARTIFACT_NAMES):
        _verify_record(
            artifact_paths[name],
            artifact_records[name],
            label=f"completion.artifacts[{index}] after verification",
        )
    _verify_record(
        completion_path,
        _record_dict(completion_record),
        label="trusted completion after verification",
    )
    result = {
        "schema": VERIFICATION_SCHEMA,
        "verified": True,
        "scientific_result": True,
        "run_dir": _portable_path(run_dir),
        "completion_sha256": completion_record.sha256,
        "trusted_completion_sha256": trusted_completion_sha256,
        "analysis_sha256": analysis_record.sha256,
        "source_runs_rehashed": EXPECTED_RUNS,
        "p1_oof_matrices_recomputed": len(CANONICAL_CONDITIONS) * len(CANONICAL_SEEDS),
    }
    _assert_no_nonfinite_numbers(result, path="verification")
    return result


def write_audit(
    *,
    zip_path: Path,
    model_csv: Path,
    cells_path: Path,
    genes_path: Path,
    output_root: Path,
) -> Path:
    archive_record = validate_external_archive(zip_path)
    cohort_cells, cells_record = _read_lines_with_record(cells_path)
    cohort_genes, genes_record = _read_lines_with_record(genes_path)
    model_record = _record_dict(_file_record(model_csv))
    columns, column_metadata = read_sanger_columns(
        zip_path, expected_archive_record=archive_record
    )
    cell_matches, cell_metadata = match_cells(
        model_csv,
        cohort_cells,
        columns,
        expected_model_record=model_record,
    )
    _, gene_matches, gene_metadata = load_sanger_matrix(
        zip_path,
        cohort_genes,
        cell_matches,
        expected_archive_record=archive_record,
    )
    payload = {
        "schema": AUDIT_SCHEMA,
        "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "scientific_result": False,
        "reason": (
            "Source and mapping audit only. The complete hash-bound 99-run campaign "
            "has not been supplied, so no model result is computed."
        ),
        "external_archive": archive_record,
        "model_csv": model_record,
        "cohort_cells": _record_dict(cells_record),
        "cohort_genes": _record_dict(genes_record),
        "mapping": {
            **column_metadata,
            **cell_metadata,
            **gene_metadata,
            "exact_unique_matched_cells": len(cell_matches),
            "exact_unique_matched_genes": len(gene_matches),
        },
    }
    output_root.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%dT%H%M%S", time.gmtime())
    path = (
        output_root / f"source-audit-{stamp}.{time.time_ns() % 1_000_000_000:09d}Z.json"
    )
    _atomic_json(path, payload)
    return path


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    freeze = subparsers.add_parser(
        "freeze",
        help="create a write-once post-access/source-audit analysis lock",
    )
    freeze.add_argument("--output", type=Path, default=DEFAULT_PROTOCOL_FREEZE)
    freeze.add_argument("--campaign-report", type=Path, required=True)
    freeze.add_argument("--zip", type=Path, default=DEFAULT_ZIP)
    freeze.add_argument("--model-csv", type=Path, default=DEFAULT_MODEL_CSV)
    freeze.add_argument("--cells", type=Path, default=DEFAULT_CELLS)
    freeze.add_argument("--genes", type=Path, default=DEFAULT_GENES)

    audit = subparsers.add_parser("audit", help="validate fixed source data only")
    audit.add_argument("--zip", type=Path, default=DEFAULT_ZIP)
    audit.add_argument("--model-csv", type=Path, default=DEFAULT_MODEL_CSV)
    audit.add_argument("--cells", type=Path, default=DEFAULT_CELLS)
    audit.add_argument("--genes", type=Path, default=DEFAULT_GENES)
    audit.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)

    run = subparsers.add_parser("run", help="run formal validation")
    run.add_argument("--campaign-report", type=Path, required=True)
    run.add_argument("--zip", type=Path, default=DEFAULT_ZIP)
    run.add_argument("--model-csv", type=Path, default=DEFAULT_MODEL_CSV)
    run.add_argument("--cells", type=Path, default=DEFAULT_CELLS)
    run.add_argument("--genes", type=Path, default=DEFAULT_GENES)
    run.add_argument("--protocol-freeze", type=Path, default=DEFAULT_PROTOCOL_FREEZE)
    run.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)

    verify = subparsers.add_parser(
        "verify", help="independently recompute a formal run"
    )
    verify.add_argument("run_dir", type=Path)
    verify.add_argument(
        "--trusted-completion-sha256",
        required=True,
        help="externally recorded SHA-256 of completion.json",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "freeze":
            path = freeze_protocol(
                args.output,
                campaign_report=args.campaign_report,
                zip_path=args.zip,
                model_csv=args.model_csv,
                cells_path=args.cells,
                genes_path=args.genes,
            )
            print(path)
            return 0
        if args.command == "audit":
            path = write_audit(
                zip_path=args.zip,
                model_csv=args.model_csv,
                cells_path=args.cells,
                genes_path=args.genes,
                output_root=args.output_root,
            )
            print(path)
            return 0
        if args.command == "run":
            analysis, bindings = build_analysis(
                campaign_report=args.campaign_report,
                zip_path=args.zip,
                model_csv=args.model_csv,
                cells_path=args.cells,
                genes_path=args.genes,
                protocol_freeze=args.protocol_freeze,
            )
            path = write_formal_run(analysis, bindings, args.output_root)
            print(path)
            return 0
        report = verify_run(
            args.run_dir,
            trusted_completion_sha256=args.trusted_completion_sha256,
        )
        json.dump(report, sys.stdout, indent=2, sort_keys=True)
        sys.stdout.write("\n")
        return 0
    except ValidationError as exc:
        print(f"[sanger-validation] ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
