def _runtime_fingerprint_sha256(run_manifest: Mapping[str, Any]) -> str:
    """Recompute the campaign aggregator's canonical runtime fingerprint."""
    device_type = run_manifest.get("device")
    if device_type not in {"cpu", "cuda"}:
        raise ValidationError("run manifest has an invalid runtime device")
    runtime = run_manifest.get("runtime")
    versions = run_manifest.get("versions")
    if not isinstance(runtime, dict) or not isinstance(versions, dict):
        raise ValidationError("run manifest lacks runtime or version provenance")
    version_names = ("numpy", "pandas", "scipy", "scikit_learn", "torch")
    if any(
        not isinstance(versions.get(name), str) or not versions[name]
        for name in version_names
    ):
        raise ValidationError("run manifest has incomplete runtime package versions")
    if not isinstance(runtime.get("amp_enabled"), bool):
        raise ValidationError("run manifest amp_enabled is not boolean")
    if not isinstance(runtime.get("cuda_available"), bool):
        raise ValidationError("run manifest cuda_available is not boolean")
    expected_amp = device_type == "cuda"
    expected_precision = "bfloat16" if expected_amp else None
    if (
        runtime.get("amp_enabled") is not expected_amp
        or runtime.get("amp_precision") != expected_precision
    ):
        raise ValidationError("run manifest AMP policy does not match its device")
    capability = runtime.get("cuda_device_capability")
    for field in ("torch_cuda_version", "cuda_device_name"):
        value = runtime.get(field)
        if value is not None and (not isinstance(value, str) or not value):
            raise ValidationError(f"run manifest {field} is invalid")
    cudnn_version = runtime.get("cudnn_version")
    if cudnn_version is not None and (
        isinstance(cudnn_version, bool)
        or not isinstance(cudnn_version, int)
        or cudnn_version < 0
    ):
        raise ValidationError("run manifest cudnn_version is invalid")
    if device_type == "cpu":
        if capability is not None or runtime.get("cuda_device_name") is not None:
            raise ValidationError("CPU run contains CUDA device identity")
    elif (
        runtime.get("cuda_available") is not True
        or runtime.get("torch_cuda_version") is None
        or cudnn_version is None
        or runtime.get("cuda_device_name") is None
        or not isinstance(capability, list)
        or len(capability) != 2
        or any(
            isinstance(value, bool) or not isinstance(value, int) or value < 0
            for value in capability
        )
    ):
        raise ValidationError("CUDA run has incomplete accelerator identity")
    for field in ("python", "platform"):
        if not isinstance(run_manifest.get(field), str) or not run_manifest[field]:
            raise ValidationError(f"run manifest {field} is empty")
    fingerprint = {
        "device_type": device_type,
        "amp_enabled": runtime.get("amp_enabled"),
        "amp_precision": runtime.get("amp_precision"),
        "cuda_available": runtime.get("cuda_available"),
        "torch_cuda_version": runtime.get("torch_cuda_version"),
        "cudnn_version": runtime.get("cudnn_version"),
        "cuda_device_name": runtime.get("cuda_device_name"),
        "cuda_device_capability": capability,
        "python": run_manifest["python"],
        "platform": run_manifest["platform"],
        "versions": {name: versions[name] for name in version_names},
    }
    canonical = json.dumps(
        fingerprint, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


