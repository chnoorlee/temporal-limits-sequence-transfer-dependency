def _stat_signature(value: os.stat_result) -> tuple[int, int, int, int]:
    return (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns)


def _stable_hash_and_size(
    path: Path, chunk_size: int = 4 * 1024 * 1024
) -> tuple[str, int]:
    """Hash one stable file instance and reject replacement during the read."""
    path = path.resolve()
    try:
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            before = os.fstat(handle.fileno())
            while chunk := handle.read(chunk_size):
                digest.update(chunk)
            after = os.fstat(handle.fileno())
        current = path.stat()
    except OSError as exc:
        raise ValidationError(f"required file cannot be read: {path}") from exc
    if _stat_signature(before) != _stat_signature(after) or _stat_signature(
        after
    ) != _stat_signature(current):
        raise ValidationError(f"file changed while it was being hashed: {path}")
    return digest.hexdigest(), int(after.st_size)


def _stable_read_bytes(path: Path) -> tuple[bytes, FileRecord]:
    """Read a small file once and bind the bytes to the opened file instance."""
    path = path.resolve()
    try:
        with path.open("rb") as handle:
            before = os.fstat(handle.fileno())
            payload = handle.read()
            after = os.fstat(handle.fileno())
        current = path.stat()
    except OSError as exc:
        raise ValidationError(f"required file cannot be read: {path}") from exc
    if _stat_signature(before) != _stat_signature(after) or _stat_signature(
        after
    ) != _stat_signature(current):
        raise ValidationError(f"file changed while it was being read: {path}")
    digest = hashlib.sha256(payload).hexdigest()
    return payload, FileRecord(
        path=_portable_path(path), bytes=len(payload), sha256=digest
    )


def _sha256_file(path: Path, chunk_size: int = 4 * 1024 * 1024) -> str:
    digest, _ = _stable_hash_and_size(path, chunk_size)
    return digest


def _file_record(path: Path) -> FileRecord:
    path = path.resolve()
    if not path.is_file():
        raise ValidationError(f"required file does not exist: {path}")
    digest, size = _stable_hash_and_size(path)
    return FileRecord(path=_portable_path(path), bytes=size, sha256=digest)


def _record_dict(record: FileRecord) -> dict[str, Any]:
    return {"path": record.path, "bytes": record.bytes, "sha256": record.sha256}


def _read_lines(path: Path) -> list[str]:
    values, _ = _read_lines_with_record(path)
    return values


def _read_lines_with_record(path: Path) -> tuple[list[str], FileRecord]:
    payload, record = _stable_read_bytes(path)
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ValidationError(f"identifier list is not valid UTF-8: {path}") from exc
    values = [line.strip() for line in text.splitlines()]
    if not values or any(not value for value in values):
        raise ValidationError(
            f"identifier list is empty or contains blank values: {path}"
        )
    if len(values) != len(set(values)):
        raise ValidationError(f"identifier list contains duplicates: {path}")
    return values, record


def _read_bound_lines(
    path: Path, expected: Mapping[str, Any], *, label: str
) -> list[str]:
    values, observed = _read_lines_with_record(path)
    _assert_observed_record(observed, expected, label=label)
    return values


def _safe_child(base: Path, relative: str) -> Path:
    if not isinstance(relative, str) or not relative:
        raise ValidationError("artifact path must be a non-empty string")
    candidate = (base / relative).resolve()
    try:
        candidate.relative_to(base.resolve())
    except ValueError as exc:
        raise ValidationError(
            f"artifact path escapes run directory: {relative}"
        ) from exc
    return candidate


def _verify_record(path: Path, record: Mapping[str, Any], *, label: str) -> None:
    if not path.is_file():
        raise ValidationError(f"{label} is missing: {path}")
    expected_bytes = record.get("bytes")
    expected_sha = record.get("sha256")
    if not isinstance(expected_bytes, int) or expected_bytes < 0:
        raise ValidationError(f"{label}.bytes is invalid")
    if not isinstance(expected_sha, str) or len(expected_sha) != 64:
        raise ValidationError(f"{label}.sha256 is invalid")
    observed_sha, observed_bytes = _stable_hash_and_size(path)
    if observed_bytes != expected_bytes:
        raise ValidationError(f"{label} byte count changed: {path}")
    if observed_sha != expected_sha:
        raise ValidationError(f"{label} SHA-256 changed: {path}")


def _record_path(record: Mapping[str, Any], *, label: str) -> Path:
    return _resolve_bound_path(record.get("path"), label=f"{label}.path")


def _assert_observed_record(
    observed: FileRecord,
    expected: Mapping[str, Any],
    *,
    label: str,
    check_path: bool = True,
) -> None:
    """Compare bytes consumed from one open instance with their binding."""
    expected_bytes = expected.get("bytes")
    expected_sha = expected.get("sha256")
    if not isinstance(expected_bytes, int) or expected_bytes < 0:
        raise ValidationError(f"{label}.bytes is invalid")
    if not _valid_sha256(expected_sha):
        raise ValidationError(f"{label}.sha256 is invalid")
    if check_path:
        expected_path = _record_path(expected, label=label)
        observed_path = _resolve_bound_path(
            observed.path, label=f"{label}.observed_path"
        )
        if observed_path != expected_path:
            raise ValidationError(
                f"{label} consumed an unexpected path: {observed.path}"
            )
    if observed.bytes != expected_bytes:
        raise ValidationError(f"{label} consumed byte count does not match its binding")
    if observed.sha256 != expected_sha:
        raise ValidationError(f"{label} consumed SHA-256 does not match its binding")


def _hash_open_binary(
    handle: BinaryIO, chunk_size: int = 4 * 1024 * 1024
) -> tuple[str, int]:
    handle.seek(0)
    digest = hashlib.sha256()
    size = 0
    while chunk := handle.read(chunk_size):
        digest.update(chunk)
        size += len(chunk)
    return digest.hexdigest(), size


@contextmanager
def _open_bound_binary(
    path: Path,
    *,
    label: str,
    expected: Mapping[str, Any] | None = None,
    check_expected_path: bool = True,
) -> Iterator[tuple[BinaryIO, FileRecord]]:
    """Hash, consume and re-hash the same open file instance."""
    path = path.resolve()
    handle: BinaryIO | None = None
    try:
        handle = path.open("rb")
        before = os.fstat(handle.fileno())
        digest, size = _hash_open_binary(handle)
        after_hash = os.fstat(handle.fileno())
        current = path.stat()
        if _stat_signature(before) != _stat_signature(after_hash) or _stat_signature(
            after_hash
        ) != _stat_signature(current):
            raise ValidationError(f"{label} changed while it was being hashed")
        observed = FileRecord(path=_portable_path(path), bytes=size, sha256=digest)
        if expected is not None:
            _assert_observed_record(
                observed,
                expected,
                label=label,
                check_path=check_expected_path,
            )
        handle.seek(0)
        try:
            yield handle, observed
        finally:
            after_use = os.fstat(handle.fileno())
            current_after_use = path.stat()
            final_digest, final_size = _hash_open_binary(handle)
            after_final_hash = os.fstat(handle.fileno())
            current_after_hash = path.stat()
            signatures = (
                before,
                after_use,
                current_after_use,
                after_final_hash,
                current_after_hash,
            )
            if any(
                _stat_signature(value) != _stat_signature(before)
                for value in signatures[1:]
            ) or (final_digest, final_size) != (digest, size):
                raise ValidationError(f"{label} changed while it was being consumed")
    except OSError as exc:
        raise ValidationError(f"{label} cannot be read: {path}") from exc
    finally:
        if handle is not None:
            handle.close()


def _assert_bound_input(
    requested: Path, record: Mapping[str, Any], *, label: str
) -> Path:
    expected = _record_path(record, label=label)
    requested = requested.resolve()
    if requested != expected:
        raise ValidationError(
            f"{label} path differs from the post-access protocol lock: {requested}"
        )
    _verify_record(requested, record, label=label)
    return requested


def _valid_sha256(value: Any) -> bool:
    return (
        isinstance(value, str) and len(value) == 64 and set(value).issubset(HEX_DIGITS)
    )


def _atomic_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{uuid.uuid4().hex}")
    with temporary.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, ensure_ascii=True)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def _atomic_new_json(path: Path, payload: Mapping[str, Any]) -> None:
    """Publish a new JSON file atomically and never replace an existing path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{uuid.uuid4().hex}")
    try:
        with temporary.open("xb") as handle:
            handle.write(_canonical_json_bytes(payload))
            handle.flush()
            os.fsync(handle.fileno())
        try:
            os.link(temporary, path)
        except FileExistsError as exc:
            raise ValidationError(
                f"refusing to overwrite protocol lock: {path}"
            ) from exc
    finally:
        temporary.unlink(missing_ok=True)


def _canonical_json_bytes(payload: Mapping[str, Any]) -> bytes:
    return (
        json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
        + "\n"
    ).encode("utf-8")


def _analysis_source_record() -> FileRecord:
    """Bind the bytes at the source path from which this module was imported."""
    module_spec = globals().get("__spec__")
    if module_spec is not None:
        origin = getattr(module_spec, "origin", None)
        if (
            not isinstance(origin, str)
            or Path(origin).resolve() != ANALYSIS_SOURCE_PATH
        ):
            raise ValidationError(
                "analysis module import origin does not match __file__"
            )
    record = _file_record(ANALYSIS_SOURCE_PATH)
    if record.sha256 != ANALYSIS_SOURCE_IMPORT_SHA256:
        raise ValidationError("analysis source changed after this module was imported")
    return record


def _environment_manifest() -> dict[str, Any]:
    packages = {}
    for distribution, label in (
        ("numpy", "numpy"),
        ("scipy", "scipy"),
        ("torch", "torch"),
        ("pandas", "pandas"),
    ):
        try:
            packages[label] = importlib.metadata.version(distribution)
        except importlib.metadata.PackageNotFoundError as exc:
            raise ValidationError(
                f"required runtime package metadata is missing: {distribution}"
            ) from exc
    manifest = {
        "python": platform.python_version(),
        "python_implementation": platform.python_implementation(),
        "python_cache_tag": sys.implementation.cache_tag,
        "packages": packages,
    }
    manifest["canonical_sha256"] = hashlib.sha256(
        _canonical_json_bytes(manifest)
    ).hexdigest()
    return manifest


def _archive_spec_dict(spec: ExternalArchiveSpec) -> dict[str, Any]:
    return {
        "bytes": spec.bytes,
        "sha256": spec.sha256,
        "members": list(spec.members),
        "member_metadata": {
            name: [int(values[0]), int(values[1])]
            for name, values in spec.member_metadata.items()
        },
    }


def _archive_spec_from_dict(value: Any) -> ExternalArchiveSpec:
    if not isinstance(value, Mapping):
        raise ValidationError("Project Score archive specification is invalid")
    members = value.get("members")
    metadata = value.get("member_metadata")
    if (
        not isinstance(value.get("bytes"), int)
        or value["bytes"] < 0
        or not _valid_sha256(value.get("sha256"))
        or not isinstance(members, list)
        or not members
        or any(not isinstance(name, str) or not name for name in members)
        or len(members) != len(set(members))
        or not isinstance(metadata, Mapping)
        or set(metadata) != set(members)
    ):
        raise ValidationError("Project Score archive specification is invalid")
    parsed_metadata: dict[str, tuple[int, int]] = {}
    for name in members:
        item = metadata[name]
        if (
            not isinstance(item, list)
            or len(item) != 2
            or any(not isinstance(number, int) or number < 0 for number in item)
        ):
            raise ValidationError(
                f"Project Score member specification is invalid: {name}"
            )
        parsed_metadata[name] = (item[0], item[1])
    return ExternalArchiveSpec(
        bytes=value["bytes"],
        sha256=value["sha256"],
        members=tuple(members),
        member_metadata=parsed_metadata,
    )


def _read_json_object(path: Path, *, label: str) -> tuple[dict[str, Any], FileRecord]:
    raw, record = _stable_read_bytes(path)
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValidationError(f"{label} is not valid UTF-8 JSON") from exc
    if not isinstance(value, dict):
        raise ValidationError(f"{label} must be a JSON object")
    return value, record


